"""Lossless transport packs. Original GLBs remain canonical for QA/older browsers."""
import gzip,hashlib,json,pathlib,sys
root=pathlib.Path(__file__).resolve().parents[1]
files=list((root/'modules/nature-planet/assets').glob('grade*-terrain.glb'))
for folder in ['nature-landscape-v3','nature-landscape-v4','nature-botanical-pilot','grade1-space-props']:
 files+=list((root/'assets/models'/folder).glob('*.glb'))
rows={}
for p in sorted(files):
 raw=p.read_bytes();packed=gzip.compress(raw,compresslevel=9,mtime=0);out=p.with_suffix('.glb.gzip.bin');out.write_bytes(packed)
 rows[p.relative_to(root).as_posix()]={'bytes':len(raw),'packedBytes':len(packed),'sha256':hashlib.sha256(raw).hexdigest()}
manifest=root/'modules/nature-planet/runtime/asset-packs.mjs'
expected='// Generated by scripts/pack-nature-assets.py; lossless original-byte identity.\nexport const assetPacks = '+json.dumps(rows,indent=2)+';\n'
if '--verify-manifest' in sys.argv:
 if manifest.read_text()!=expected: raise SystemExit('Transport manifest mismatch: regenerate and review asset-packs.mjs before deployment')
else: manifest.write_text(expected)
print('original',sum(r['bytes'] for r in rows.values()),'packed',sum(r['packedBytes'] for r in rows.values()))
